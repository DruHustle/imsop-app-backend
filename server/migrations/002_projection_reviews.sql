-- Do not infer provider/owner of legacy rows. Release preflight lists unresolved identities.
ALTER TABLE shipments DROP CONSTRAINT shipments_tracking_number_key;
ALTER TABLE shipments ADD COLUMN provider varchar(100), ADD COLUMN snapshot_event_id integer REFERENCES logistics_events(id),
 ADD COLUMN observed_at timestamp, ADD COLUMN received_at timestamp,
 ADD COLUMN promised_arrival timestamp, ADD COLUMN projection_version integer NOT NULL DEFAULT 0;
CREATE UNIQUE INDEX shipments_identity ON shipments(workspace_id,provider,tracking_number);
ALTER TABLE logistics_events DROP CONSTRAINT uq_logistics_provider_event;
CREATE UNIQUE INDEX uq_logistics_workspace_provider_event ON logistics_events(workspace_id,provider,event_id);
CREATE INDEX logistics_projection_order ON logistics_events(workspace_id,provider,tracking_number,occurred_at,event_id COLLATE "C");
CREATE INDEX shipments_workspace_status ON shipments(workspace_id,status,id DESC);
CREATE TABLE review_cases (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id uuid NOT NULL REFERENCES workspaces(id),
 shipment_id integer NOT NULL REFERENCES shipments(id), state text NOT NULL DEFAULT 'open' CHECK(state IN ('open','acknowledged','resolved')),
 assignee_id integer REFERENCES users(id), updated_at timestamptz NOT NULL DEFAULT now(), version integer NOT NULL DEFAULT 0,
 UNIQUE(workspace_id,shipment_id)
);
CREATE TABLE review_actions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id uuid NOT NULL REFERENCES workspaces(id),
 case_id integer NOT NULL REFERENCES review_cases(id), actor_id integer REFERENCES users(id),
 action text NOT NULL, note text, occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE notification_reads (
 user_id integer NOT NULL REFERENCES users(id), action_id integer NOT NULL REFERENCES review_actions(id),
 read_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(user_id,action_id)
);
